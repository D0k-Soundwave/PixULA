/**
 * Sine ripple. Sampling y == f(x) alone leaves the line dashed wherever the curve climbs
 * faster than one row per column, so fill the span between adjacent samples instead.
 */
const ripple = (size, amp, lines) => {
    const at = (x) => Math.round((size / 2) + amp * Math.sin((x / size) * Math.PI * 2));
    return fromFn(size, (x, y) => {
        const lo = Math.min(at(x), at(x + 1));
        const hi = Math.max(at(x), at(x + 1));
        return lines.some((off) => {
            const yy = ((y - off) % size + size) % size;
            return yy >= lo && yy <= hi;
        });
    });
};

