/** Smallest px/py the tile actually repeats on — a 16x16 tile with period 8 is a lie. */
function period(e) {
    const at = (x, y) => e.bmp[y * e.w + x];
    let px = e.w;
    for (let p = 1; p < e.w; p++) {
        if (e.w % p) continue;
        let ok = true;
        for (let y = 0; y < e.h && ok; y++) for (let x = 0; x < e.w; x++) if (at(x, y) !== at((x + p) % e.w, y)) { ok = false; break; }
        if (ok) { px = p; break; }
    }
    let py = e.h;
    for (let p = 1; p < e.h; p++) {
        if (e.h % p) continue;
        let ok = true;
        for (let y = 0; y < e.h && ok; y++) for (let x = 0; x < e.w; x++) if (at(x, y) !== at(x, (y + p) % e.h)) { ok = false; break; }
        if (ok) { py = p; break; }
    }
    return Math.max(px, py);
}

const seen = new Map();
const problems = [];
for (const [key, e] of Object.entries(LIB)) {
    const ink = e.bmp.reduce((a, v) => a + v, 0);
    const total = e.w * e.h;
    if (ink === 0 || ink === total) problems.push(`${key}: blank or solid`);
    const sig = `${e.w}x${e.h}:${e.bmp.join('')}`;
    if (seen.has(sig)) problems.push(`${key}: identical to ${seen.get(sig)}`);
    else seen.set(sig, key);

    // A tile only earns its tier if it repeats on a period larger than the tier below it.
    // Otherwise it is the smaller pattern stamped twice, and belongs in the smaller tier.
    if (e.w > 8 && period(e) <= e.w / 2) {
        problems.push(`${key}: repeats every ${period(e)}px — belongs in the ${e.w / 2}x${e.h / 2} set`);
    }

    const m = key.match(/density-(\d+)$/);
    if (m) {
        const want = Number(m[1]) / 100;
        const got = ink / total;
        if (Math.abs(want - got) > 0.02) {
            problems.push(`${key}: name promises ${(want * 100).toFixed(0)}% ink, bitmap has ${(got * 100).toFixed(1)}%`);
        }
    }
}
if (problems.length) {
    console.error('PATTERN LIBRARY INVALID:');
    problems.forEach((p) => console.error('  - ' + p));
    process.exit(1);
}

