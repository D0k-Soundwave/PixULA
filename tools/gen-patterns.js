'use strict';
/**
 * gen-patterns.js — generates js/data/pattern-bitmaps.js (the pattern library).
 *
 * Run: node tools/gen-patterns.js
 *
 * The library is a SHADING system first: on a two-colour ZX cell the only way to
 * fake a grey is to dither, so the SPINE of the set is the generated ramp below —
 * an ordered density ramp exact by construction (Bayer thresholds, not eyeballed),
 * plus the clustered-dot and noise dispersions of the same greys. That half is
 * computed, so it cannot drift from the coverage its name promises.
 *
 * The other half is the hand-authored designs: line and hatch families, and the
 * tiling motifs that still read once rasterised to 1 bit. Those are ASCII art in
 * this file, so the artwork is reviewable in a diff.
 *
 * Detail does not survive at 8x8. Anything that reads as noise is not a pattern,
 * it IS noise — hence a curated set rather than a big evocative one, and a tile is
 * filed at the size it genuinely repeats on (the validator at the foot enforces it).
 *
 * Output shape (consumed by PatternService + PatternPanel):
 *   window.PATTERN_BITMAPS = { "8x8/density-25": { w, h, c: category, d: base64 }, ... }
 * base64 is the 1-bit bitmap, row-major, MSB = first pixel (PatternService._decodeBitmap).
 */

const fs = require('fs');
const path = require('path');

// ---------------------------------------------------------------- bitmap helpers

/** Build from ASCII rows: '#' = ink, anything else = paper. */
function fromAscii(rows) {
    const h = rows.length;
    const w = rows[0].length;
    const bmp = new Uint8Array(w * h);
    rows.forEach((row, y) => {
        if (row.length !== w) throw new Error(`ragged ascii row ${y}: "${row}"`);
        for (let x = 0; x < w; x++) bmp[y * w + x] = row[x] === '#' ? 1 : 0;
    });
    return { w, h, bmp };
}

/** Build from a predicate over (x, y). */
function fromFn(size, fn) {
    const bmp = new Uint8Array(size * size);
    for (let y = 0; y < size; y++) {
        for (let x = 0; x < size; x++) bmp[y * size + x] = fn(x, y) ? 1 : 0;
    }
    return { w: size, h: size, bmp };
}

function pack(entry) {
    const { w, h, bmp } = entry;
    const bytes = Buffer.alloc(Math.ceil((w * h) / 8));
    for (let i = 0; i < w * h; i++) {
        if (bmp[i]) bytes[i >> 3] |= 1 << (7 - (i & 7));
    }
    return bytes.toString('base64');
}

// ---------------------------------------------------------------- dither matrices

/** Recursive Bayer: B(2n) = [[4B, 4B+2], [4B+3, 4B+1]]. */
function bayer(order) {
    let m = [[0]];
    for (let s = 1; s < order; s *= 2) {
        const n = m.length;
        const next = Array.from({ length: n * 2 }, () => new Array(n * 2).fill(0));
        for (let y = 0; y < n; y++) {
            for (let x = 0; x < n; x++) {
                const v = 4 * m[y][x];
                next[y][x] = v;
                next[y][x + n] = v + 2;
                next[y + n][x] = v + 3;
                next[y + n][x + n] = v + 1;
            }
        }
        m = next;
    }
    return m;
}

const B2 = bayer(2);
const B4 = bayer(4);
const B8 = bayer(8);

/**
 * Classic 45-degree clustered-dot (halftone screen) matrix. Unlike Bayer, the set
 * pixels clump into a growing dot — the newspaper look, and the one that survives
 * the ZX's non-square pixel aspect best at low densities.
 */
const CLUSTER8 = [
    [24, 10, 12, 26, 35, 47, 49, 37],
    [8, 0, 2, 14, 45, 59, 61, 51],
    [22, 6, 4, 16, 43, 57, 63, 53],
    [30, 20, 18, 28, 33, 41, 55, 39],
    [34, 46, 48, 38, 25, 11, 13, 27],
    [44, 58, 60, 50, 9, 1, 3, 15],
    [42, 56, 62, 52, 23, 7, 5, 17],
    [32, 40, 54, 36, 31, 21, 19, 29]
];

/** Exact-coverage threshold: sets level/steps of the pixels. */
function ramp(matrix, level, steps, size) {
    const n = matrix.length;
    const cut = (level * n * n) / steps;
    return fromFn(size, (x, y) => matrix[y % n][x % n] < cut);
}

// ---------------------------------------------------------------- the library

const LIB = {};
const add = (size, name, category, entry) => {
    const key = `${size}x${size}/${name}`;
    if (LIB[key]) throw new Error(`duplicate key ${key}`);
    LIB[key] = { c: category, ...entry };
};

// --- density: the ramp, and the reason the library exists. Bayer thresholds, so the
// coverage is exact by construction. Bayer is RECURSIVE — thresholding the 8x8 matrix
// at k/8 reproduces the 4x4 and 2x2 matrices at the same coverage, pixel for pixel — so
// there is no separate "Bayer 2x2/4x4/8x8" family to ship: for a given dispersed
// coverage there is exactly one pattern. The 06/94 ends are the subtle-shading steps.
[[1, 16], [1, 8], [1, 4], [3, 8], [1, 2], [5, 8], [3, 4], [7, 8], [15, 16]].forEach(([num, den]) => {
    const pct = String(Math.round((num / den) * 100)).padStart(2, '0');
    add(8, `density-${pct}`, 'density', ramp(B8, num, den, 8));
});

// --- halftone: clustered dot (the growing-dot newspaper screen). Genuinely different
// from Bayer at the same coverage: the ink clumps instead of dispersing, which holds
// together better over small areas and on a CRT.
[16, 24, 32, 40, 48].forEach((cut) => {
    const pct = String(Math.round((cut / 64) * 100)).padStart(2, '0');
    add(8, `halftone-${pct}`, 'halftone', fromFn(8, (x, y) => CLUSTER8[y][x] < cut));
});

// --- noise: the third dispersion. Deterministic hash, no matrix structure, so it
// breaks up the banding that ordered dither shows across a large flat fill.
const hash = (x, y) => {
    let h = (x * 374761393 + y * 668265263) >>> 0;
    h = (h ^ (h >>> 13)) >>> 0;
    h = Math.imul(h, 1274126177) >>> 0;
    return ((h ^ (h >>> 16)) >>> 0) % 64;
};
